from math import sqrt, comb
z = 1.959964
def wilson(k, n, z=z):
    p = k / n; d = 1 + z*z/n
    c = (p + z*z/(2*n)) / d
    h = z * sqrt(p*(1-p)/n + z*z/(4*n*n)) / d
    return c - h, c + h
def binom_sf(k, n, p):  # P(K >= k)
    return sum(comb(n, i) * p**i * (1-p)**(n-i) for i in range(k, n+1))
